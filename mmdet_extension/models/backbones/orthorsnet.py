# Ridge added to the basis Gram matrix. The basis is C x k with k << C, so the
# k x k solve is cheap; the ridge only keeps the projection well-conditioned
# while the basis is still small.
_BASIS_EPS = 1e-3


def _replicate_pad(x, pad_h, pad_w):
    if pad_h == 0 and pad_w == 0:
        return x
    # Replicate rather than reflect: reflect needs pad < size, which fails on
    # the 25x25 C5 maps.
    return F.pad(x, (pad_w, pad_w, pad_h, pad_h), mode='replicate')


def _local_mean(x, span):
    """Stride-one local mean over a ``span x span`` window."""
    padded = _replicate_pad(x, span // 2, span // 2)
    return F.avg_pool2d(padded, span, stride=1)


class SpeckleAwareLocalNorm(nn.Module):
    """M1: gain-invariant local contrast normalisation (CFAR-style front end).

    The correction is ``x * (1 + gamma * tanh(proj(z)))`` with ``proj``'s output
    layer zero-initialized, so a fresh module is an exact identity.

    ``z`` is the local standard score of the input, which is invariant to any
    positive rescaling of the input: multiplying the image by ``a`` multiplies
    both the local mean and the local standard deviation by ``a``, so their
    ratio is unchanged. That is the property a multiplicative-gain corruption
    (brightness, contrast, sensor gain) violates and this module restores.
    """

    def __init__(self,
                 channels=3,
                 window=5,
                 eps=1e-4,
                 gamma=0.5,
                 hidden_channels=16,
                 learnable_affine=True,
                 log_input=False,
                 use_variance=True):
        super().__init__()
        if channels <= 0:
            raise ValueError('channels must be positive')
        if window < 1 or window % 2 == 0:
            raise ValueError(
                f'window must be a positive odd integer; got {window}')
        if eps <= 0.0:
            raise ValueError('eps must be positive')
        if not 0.0 <= gamma <= 1.0:
            raise ValueError('gamma must be in [0, 1]')
        if hidden_channels <= 0:
            raise ValueError('hidden_channels must be positive')

        self.channels = int(channels)
        self.window = int(window)
        self.eps = float(eps)
        self.gamma = float(gamma)
        self.log_input = bool(log_input)
        self.use_variance = bool(use_variance)
        self.learnable_affine = bool(learnable_affine)

        if self.learnable_affine:
            self.weight = nn.Parameter(torch.ones(self.channels))
            self.bias = nn.Parameter(torch.zeros(self.channels))

        self.proj = nn.Sequential(
            nn.Conv2d(self.channels, hidden_channels, 1),
            nn.ReLU(inplace=True),
            nn.Conv2d(hidden_channels, self.channels, 1),
        )
        nn.init.zeros_(self.proj[-1].weight)
        nn.init.zeros_(self.proj[-1].bias)

    def local_contrast(self, x):
        x_ref = torch.log1p(x.clamp_min(0.0)) if self.log_input else x
        mean = _local_mean(x_ref, self.window)
        if not self.use_variance:
            return x_ref - mean
        mean_sq = _local_mean(x_ref * x_ref, self.window)
        var = (mean_sq - mean * mean).clamp_min(0.0)
        return (x_ref - mean) / torch.sqrt(var + self.eps)

    def forward(self, x):
        if x.ndim != 4 or x.shape[1] != self.channels:
            raise ValueError(
                'radiometric front end expects [B, C, H, W] with '
                f'C={self.channels}; got {tuple(x.shape)}')
        z = self.local_contrast(x)
        if self.learnable_affine:
            z = z * self.weight.view(1, -1, 1, 1) + self.bias.view(1, -1, 1, 1)
        correction = torch.tanh(self.proj(z))
        return x * (1.0 + self.gamma * correction)


def rotate_kernel_2d(kernel, theta_deg):
    """Rotate a ``[N, C, k, k]`` convolution kernel about its centre.

    Bilinear resampling on the ``k x k`` grid, so the operation is cheap (49
    sample points for the default k=7) and differentiable with respect to the
    template. Corners that fall outside the kernel window become zero, which
    shrinks the rotated kernel's norm; callers that care renormalize.
    """
    if kernel.ndim != 4 or kernel.shape[-1] != kernel.shape[-2]:
        raise ValueError(
            f'kernel must be [N, C, k, k]; got {tuple(kernel.shape)}')
    angle = math.radians(theta_deg)
    cos, sin = math.cos(angle), math.sin(angle)
    theta = kernel.new_tensor(
        [[cos, -sin, 0.0], [sin, cos, 0.0]]).unsqueeze(0)
    theta = theta.expand(kernel.shape[0], -1, -1)
    grid = F.affine_grid(theta, list(kernel.shape), align_corners=False)
    return F.grid_sample(
        kernel, grid, mode='bilinear', padding_mode='zeros',
        align_corners=False)


def project_out_subspace(residual, basis, ridge=_BASIS_EPS):
    """Remove the ``basis`` column space from ``residual``.

    ``r - r A (A^T A + ridge I)^(-1) A^T``. With ``ridge > 0`` this is the
    ridge-softened orthogonal projection: it equals ``(I - B B^T) r`` up to
    ``O(ridge)`` once ``A`` spans a well-conditioned subspace, and it needs
    only a ``k x k`` solve instead of a ``C x C`` projection matrix.

    The design note specified a QR/polar orthonormalization. That was
    implemented first and rejected: ``torch.linalg.eigh`` has no usable
    gradient at a zero or degenerate basis (the eigenvector derivative divides
    by eigenvalue gaps), and it produced NaN gradients after the first
    optimizer step. The ridge form is smooth everywhere, and at ``A = 0`` it is
    exactly the identity (``solve`` of a zero right-hand side is zero).

    ``basis`` is ``[C, k]``, ``residual`` is ``[..., C]``.
    """
    if basis.ndim != 2:
        raise ValueError(f'basis must be [C, k]; got {tuple(basis.shape)}')
    if ridge <= 0.0:
        raise ValueError('ridge must be positive')
    gram = basis.t() @ basis
    gram = gram + ridge * torch.eye(
        gram.shape[0], dtype=gram.dtype, device=gram.device)
    coeff = torch.linalg.solve(gram, (residual @ basis).transpose(-1, -2))
    return residual - coeff.transpose(-1, -2) @ basis.t()


class OrthoSubspaceAttention(nn.Module):
    """M3: OSP channel gate plus a strip-pooled spatial gate.

    ``channel_gate = 2 * sigmoid(fc(r))`` where
    ``r = (I - B B^T)(pooled - bg_mean)``. ``bg_mean`` is the learned
    radiometric background prototype and ``B`` the learned background
    subspace, so ``r`` keeps only what the background model cannot explain.
    ``B`` is stored un-normalized and the projection is the ridge form of
    :func:`project_out_subspace`.

    ``spatial_gate = 2 * sigmoid(strip_h(row_profile) + strip_w(col_profile))``
    is broadcast back over the map. The two profiles are the row and column
    means, i.e. what a horizontal or vertical structure preserves and a blob
    does not, at ``O(H + W)`` cost rather than the ``O(H * W)`` of non-local
    attention.

    Both gates are exactly 1.0 at initialization: the channel MLP's output
    layer and both depthwise strip convolutions are zero-initialized, so the
    sigmoid evaluates at 0.5 and the factor of two recovers unity.
    """

    def __init__(self,
                 channels,
                 reduction=16,
                 basis_rank=32,
                 strip_pool=True,
                 strip_kernel=7,
                 identity_init=True,
                 basis_ridge=_BASIS_EPS,
                 basis_init_scale=None,
                 eps=1e-5):
        super().__init__()
        if channels <= 0:
            raise ValueError('channels must be positive')
        if reduction <= 0:
            raise ValueError('reduction must be positive')
        if basis_rank < 0:
            raise ValueError('basis_rank must be non-negative')
        if strip_kernel < 1 or strip_kernel % 2 == 0:
            raise ValueError(
                f'strip_kernel must be a positive odd integer; '
                f'got {strip_kernel}')
        if eps <= 0.0:
            raise ValueError('eps must be positive')

        self.channels = int(channels)
        self.reduction = int(reduction)
        self.basis_rank = int(basis_rank)
        self.strip_pool = bool(strip_pool)
        self.strip_kernel = int(strip_kernel)
        self.identity_init = bool(identity_init)
        self.basis_ridge = float(basis_ridge)
        self.eps = float(eps)
        if self.basis_ridge <= 0.0:
            raise ValueError('basis_ridge must be positive')
        self.gate_scale = 2.0 if self.identity_init else 1.0

        hidden_channels = max(self.channels // self.reduction, 1)
        self.fc = nn.Sequential(
            nn.Linear(self.channels, hidden_channels, bias=False),
            nn.ReLU(inplace=True),
            nn.Linear(hidden_channels, self.channels, bias=False),
            nn.Sigmoid(),
        )

        self.bg_mean = nn.Parameter(torch.zeros(self.channels))
        if self.basis_rank > 0:
            # Random, not zero. A zero basis sits on a stationary point of the
            # ridge projection: the correction is O(||A||^2), so its gradient
            # at A = 0 is exactly zero and the subspace would never train.
            # Scale 1/sqrt(C) makes A^T A ~= I, i.e. a well-conditioned basis
            # whose projection removes ~k/C of the residual from the start.
            # This does not break the identity initialization: the channel
            # MLP's output layer is zero, so the gate is 1.0 whatever the
            # residual is.
            scale = (basis_init_scale if basis_init_scale is not None
                     else self.channels ** -0.5)
            self.bg_basis = nn.Parameter(
                torch.randn(self.channels, self.basis_rank) * scale)

        if self.strip_pool:
            self.strip_h = nn.Conv2d(
                self.channels, self.channels,
                kernel_size=(self.strip_kernel, 1),
                padding=(self.strip_kernel // 2, 0),
                groups=self.channels)
            self.strip_w = nn.Conv2d(
                self.channels, self.channels,
                kernel_size=(1, self.strip_kernel),
                padding=(0, self.strip_kernel // 2),
                groups=self.channels)
            for module in (self.strip_h, self.strip_w):
                nn.init.zeros_(module.weight)
                nn.init.zeros_(module.bias)

        if self.identity_init:
            nn.init.zeros_(self.fc[2].weight)

        self._last_diagnostics = {}

    def background_residual(self, x):
        pooled = F.adaptive_avg_pool2d(x, 1).flatten(1)
        centered = pooled - self.bg_mean
        if self.basis_rank == 0:
            return pooled, centered
        return pooled, project_out_subspace(
            centered, self.bg_basis, self.basis_ridge)

    def forward(self, x):
        if x.ndim != 4 or x.shape[1] != self.channels:
            raise ValueError(
                'OrthoSubspaceAttention expects [B, C, H, W] with '
                f'C={self.channels}; got {tuple(x.shape)}')
        batch, channels, height, width = x.shape

        pooled, residual = self.background_residual(x)
        channel_gate = (
            self.fc(residual) * self.gate_scale).view(batch, channels, 1, 1)

        if self.strip_pool:
            row_profile = F.adaptive_avg_pool2d(x, (height, 1))
            col_profile = F.adaptive_avg_pool2d(x, (1, width))
            response = self.strip_h(row_profile) + self.strip_w(col_profile)
            # ``gate_scale`` is 2 for the identity initialization, so the
            # zero-initialized strip convolutions give exactly 1.0.
            spatial_gate = self.gate_scale * torch.sigmoid(response)
            gate = channel_gate * spatial_gate
        else:
            gate = channel_gate

        with torch.no_grad():
            self._last_diagnostics = {
                'gate_mean': gate.mean().detach(),
                'gate_std': gate.std().detach(),
                'gate_min': gate.amin().detach(),
                'gate_max': gate.amax().detach(),
                # Share of the background residual the learned basis explains.
                # Expected near k/C when the basis is spread over channels.
                'subspace_energy_fraction': (
                    (pooled - self.bg_mean - residual).pow(2).sum(1)
                    / (pooled - self.bg_mean).pow(2).sum(1).clamp_min(
                        self.eps)).mean().detach(),
            }
        return x * gate

    def get_attention_diagnostics(self):
        return {
            name: value.detach().clone()
            for name, value in self._last_diagnostics.items()
        }


class OrthoRSBottleneck(OrthoBottleneck):
    """Bottleneck whose attention is an OSP-style subspace gate."""

    def __init__(self, *args, reduction=16, attn_cfg=None, **kwargs):
        # Skip OrthoBottleneck.__init__ so no legacy attention is built.
        Bottleneck.__init__(self, *args, **kwargs)
        self.attn = OrthoSubspaceAttention(
            self.planes * self.expansion,
            reduction=reduction,
            **(attn_cfg or {}))


class OrthoRSBasicBlock(OrthoBasicBlock):
    """BasicBlock whose attention is an OSP-style subspace gate."""

    def __init__(self, *args, reduction=16, attn_cfg=None, **kwargs):
        BasicBlock.__init__(self, *args, **kwargs)
        self.attn = OrthoSubspaceAttention(
            self.norm2.num_features,
            reduction=reduction,
            **(attn_cfg or {}))


@BACKBONES.register_module()
class OrthoRSNet(OrthoNet):
    """OrthoNet with a radiometric front end, a directional stem, and OSP attention.

    ``radiometric_cfg`` and ``stem_cfg`` accept ``None`` or
    ``dict(enabled=False, ...)`` to build nothing at all, which keeps the
    legacy state-dict surface untouched. ``attn_cfg`` always builds the OSP
    attention -- it is the backbone's whole point -- and merely supplies its
    options; ``dict(enabled=False)`` is not a way to fall back to the legacy
    gate. Use ``OrthoNet`` for that.

    ``frozen_stages`` keeps its ResNet meaning for ``conv1``/``norm1`` and the
    layer stages. The radiometric and directional modules are never frozen:
    they are zero-initialized, so freezing them would pin them at zero forever.

    ``sogc_cfg`` is rejected. SOGC calibrates the legacy attention response;
    the OSP residual is a different statistic and would need its own source
    statistics instead of inheriting that module's.
    """

    arch_settings = {
        18: (OrthoRSBasicBlock, (2, 2, 2, 2)),
        34: (OrthoRSBasicBlock, (3, 4, 6, 3)),
        50: (OrthoRSBottleneck, (3, 4, 6, 3)),
        101: (OrthoRSBottleneck, (3, 4, 23, 3)),
        152: (OrthoRSBottleneck, (3, 8, 36, 3)),
    }

    _STEM_ALLOWED = {
        'orientations', 'dir_kernel_size', 'dir_channels', 'renormalize',
        'template_init_std'
    }
    _ATTN_ALLOWED = {
        'basis_rank', 'strip_pool', 'strip_kernel', 'identity_init',
        'basis_ridge', 'basis_init_scale', 'eps'
    }
    _RADIOMETRIC_ALLOWED = {
        'window', 'eps', 'gamma', 'hidden_channels', 'learnable_affine',
        'log_input', 'use_variance'
    }

    def __init__(self,
                 depth,
                 reduction=16,
                 radiometric_cfg=None,
                 stem_cfg=None,
                 attn_cfg=None,
                 sogc_cfg=None,
                 **kwargs):
        if sogc_cfg is not None and sogc_cfg.get('enabled', True):
            raise NotImplementedError(
                'OrthoRSNet does not support SOGC: SOGC calibrates the legacy '
                'orthogonal-response attention, and the OSP residual is a '
                'different statistic. Use attn_cfg with basis_rank=0 for an '
                'uncalibrated gate, or run the SOGC experiments on OrthoNet.')
        if kwargs.get('deep_stem', False):
            raise NotImplementedError(
                'OrthoRSNet requires deep_stem=False: the directional stem and '
                'the ImageNet inflation both key off conv1/norm1.')
        if attn_cfg is not None and not attn_cfg.get('enabled', True):
            raise ValueError(
                'attn_cfg cannot be disabled: OrthoRSNet always uses the OSP '
                'attention. Use OrthoNet for the legacy gate.')
        self._radiometric_cfg = self._validate_module_cfg(
            radiometric_cfg, self._RADIOMETRIC_ALLOWED, 'radiometric')
        self._stem_cfg = self._validate_module_cfg(
            stem_cfg, self._STEM_ALLOWED, 'stem')
        self._attn_cfg = self._validate_module_cfg(
            attn_cfg, self._ATTN_ALLOWED, 'attn')
        super().__init__(
            depth=depth, reduction=reduction, sogc_cfg=None, **kwargs)
        self._build_radiometric()
        self._build_directional_stem()

    # ------------------------------------------------------------------ config
    @staticmethod
    def _validate_module_cfg(cfg, allowed, name):
        if cfg is None:
            return None
        if not isinstance(cfg, dict):
            raise TypeError(f'{name}_cfg must be a dict or None')
        cfg = dict(cfg)
        if not cfg.pop('enabled', True):
            return None
        unknown = set(cfg) - allowed
        if unknown:
            raise ValueError(
                f'unknown {name}_cfg options: {sorted(unknown)}')
        return cfg

    # ------------------------------------------------------------------- build
    def make_res_layer(self, **kwargs):
        """Build the stage with the OSP attention instead of the legacy one.

        ``OrthoNet.make_res_layer`` also forwards ``attn_init``, which the OSP
        block does not accept (its identity initialization is the only mode a
        fresh OrthoRSNet should ever use).
        """
        block_kwargs = dict(reduction=self.reduction)
        if self._attn_cfg is not None:
            block_kwargs['attn_cfg'] = self._attn_cfg
        return ResLayer(**block_kwargs, **kwargs)

    def _build_radiometric(self):
        self.radiometric = None
        if self._radiometric_cfg is None:
            return
        self.radiometric = SpeckleAwareLocalNorm(
            self.conv1.in_channels, **self._radiometric_cfg)

    def _build_directional_stem(self):
        self.dir_template = None
        self.dir_fuse = None
        self._stem_orientations = ()
        if self._stem_cfg is None:
            return
        cfg = dict(self._stem_cfg)
        orientations = tuple(cfg.pop('orientations', (0, 45, 90, 135)))
        kernel_size = int(cfg.pop('dir_kernel_size', 7))
        dir_channels = int(cfg.pop('dir_channels', 8))
        renormalize = bool(cfg.pop('renormalize', True))
        init_std = cfg.pop('template_init_std', None)
        if cfg:
            raise ValueError(f'unknown stem_cfg options: {sorted(cfg)}')
        if not orientations:
            raise ValueError('stem_cfg.orientations must not be empty')
        if kernel_size < 1 or kernel_size % 2 == 0:
            raise ValueError(
                'stem_cfg.dir_kernel_size must be a positive odd integer; '
                f'got {kernel_size}')
        if dir_channels <= 0:
            raise ValueError('stem_cfg.dir_channels must be positive')

        self._stem_orientations = orientations
        self._stem_renormalize = renormalize
        self.dir_channels = dir_channels
        template = torch.empty(
            len(orientations) * dir_channels, self.conv1.in_channels,
            kernel_size, kernel_size)
        if init_std is None:
            nn.init.kaiming_normal_(
                template, mode='fan_out', nonlinearity='relu')
        else:
            nn.init.normal_(template, std=float(init_std))
        self.dir_template = nn.Parameter(template)
        fuse = nn.Conv2d(
            len(orientations) * dir_channels, self.conv1.out_channels, 1,
            bias=False)
        nn.init.zeros_(fuse.weight)
        self.dir_fuse = fuse

    def _rotated_kernels(self):
        """Directional bank: one template rotated to each configured angle."""
        if self._stem_renormalize:
            reference = self.dir_template.detach().pow(2).sum(
                dim=(1, 2, 3), keepdim=True).sqrt().clamp_min(1e-6)
        kernels = []
        for index in range(len(self._stem_orientations)):
            start = index * self.dir_channels
            block = self.dir_template[start:start + self.dir_channels]
            rotated = rotate_kernel_2d(block, self._stem_orientations[index])
            if self._stem_renormalize:
                current = rotated.pow(2).sum(
                    dim=(1, 2, 3), keepdim=True).sqrt().clamp_min(1e-6)
                rotated = rotated * (
                    reference[start:start + self.dir_channels] / current)
            kernels.append(rotated)
        return torch.cat(kernels, dim=0)

    # ----------------------------------------------------------------- forward
    def forward(self, x):
        if self.radiometric is not None:
            x = self.radiometric(x)
        stem_input = x
        x = self.conv1(stem_input)
        if self.dir_template is not None:
            directional = F.conv2d(
                stem_input, self._rotated_kernels(),
                stride=self.conv1.stride, padding=self.conv1.padding)
            # Zero-initialized fuse: the branch contributes exactly nothing
            # until it is trained, so conv1's pretrained output survives.
            x = x + self.dir_fuse(directional)
        x = self.norm1(x)
        x = self.relu(x)
        x = self.maxpool(x)
        x = self._apply_slrp(self.STEM_STAGE, x)

        outs = []
        for index, layer_name in enumerate(self.res_layers):
            x = getattr(self, layer_name)(x)
            x = self._apply_slrp(index, x)
            if index in self.out_indices:
                outs.append(x)
        return tuple(outs)

    # ------------------------------------------------------------ initialization
    def _apply_identity_initialization(self):
        """Zero the output layers that make the new modules exact identities.

        This has to run twice: once in ``__init__`` and again after
        ``init_weights``. mmdet's ``ResNet.__init__`` installs a default
        ``[Kaiming(Conv2d), Constant(1, BN)]`` ``init_cfg`` whenever the caller
        passes ``init_cfg=None``, and ``BaseModule.init_weights`` then applies
        it to *every* ``Conv2d`` in the module tree -- including these. Without
        the second pass, ``dir_fuse``, the strip convolutions and the
        radiometric projection would silently come back as random Kaiming
        tensors and every identity guarantee in this file would be false.
        """
        if getattr(self, 'radiometric', None) is not None:
            nn.init.zeros_(self.radiometric.proj[-1].weight)
            nn.init.zeros_(self.radiometric.proj[-1].bias)
        if getattr(self, 'dir_fuse', None) is not None:
            nn.init.zeros_(self.dir_fuse.weight)
        for module in self.modules():
            if isinstance(module, OrthoSubspaceAttention):
                if module.identity_init:
                    nn.init.zeros_(module.fc[2].weight)
                if module.strip_pool:
                    for strip in (module.strip_h, module.strip_w):
                        nn.init.zeros_(strip.weight)
                        nn.init.zeros_(strip.bias)

    def _has_pretrained_init_cfg(self):
        entries = self.init_cfg
        if entries is None:
            return False
        if isinstance(entries, dict):
            entries = [entries]
        return any(
            isinstance(entry, dict) and entry.get('type') == 'Pretrained'
            for entry in entries)

    def init_weights(self):
        super().init_weights()
        if self._has_pretrained_init_cfg():
            # A Pretrained init only loads; it does not touch the new
            # parameters, so their constructor values (the identities) are
            # intact -- and if the checkpoint *does* contain them (warm start
            # from a trained OrthoRSNet), re-zeroing would destroy them.
            return
        self._apply_identity_initialization()

    # -------------------------------------------------------------- diagnostics
    def iter_attention_modules(self):
        for layer_name in self.res_layers:
            for block in getattr(self, layer_name):
                if isinstance(block.attn, OrthoSubspaceAttention):
                    yield block.attn

    def get_attention_diagnostics(self):
        from collections import OrderedDict
        by_layer = OrderedDict()
        for layer_name in self.res_layers:
            entries = []
            for block in getattr(self, layer_name):
                if isinstance(block.attn, OrthoSubspaceAttention):
                    entries.append(
                        block.attn.get_attention_diagnostics())
            if entries:
                by_layer[layer_name] = entries
        return by_layer
