"""OrthoRSNet: an orthogonal-subspace backbone for remote sensing features.

The design note is ``ORTHONET_RS_V2_DESIGN.txt`` at the repository root. This
module implements its M1/M2/M3 as three additions to the existing OrthoNet
layout, all of them zero-initialized so that a freshly built network still
reproduces the ResNet-50 function it was initialized from:

``M1 SpeckleAwareLocalNorm`` (:class:`SpeckleAwareLocalNorm`)
    A radiometric front end. Remote-sensing intensity is dominated by a
    multiplicative gain (sensor gain, incidence angle, surface reflectance),
    while what identifies a target is its contrast against the local
    background. A CFAR detector is built on exactly that observation. The
    module computes a local contrast normalisation and adds a bounded,
    zero-initialized correction to the input, so it starts as the identity and
    can learn a gain-invariant representation instead of spending capacity on
    discovering one.

``M2 directional stem`` (:meth:`OrthoRSNet._rotated_kernels`)
    The geometric (G) subspace. Runways, bridges, breakwaters, wakes and
    fuselages are long, single-orientation structures; a 3x3 kernel is
    isotropic at initialization and has to learn orientation selectivity from
    data. The stem carries a directional filter bank generated by rotating one
    learnable template to the configured orientations. The bank is an additive,
    zero-initialized branch beside ``conv1``, so the ResNet stem weights still
    inflate in and the pretrained function is untouched at step zero. Because
    ``conv1``/``norm1``/``relu`` stay at the top level, the torchvision
    state-dict keys are unchanged.

``M3 OrthoSubspaceAttention`` (:class:`OrthoSubspaceAttention`)
    Replaces ``OrthogonalChannelAttention``, whose "orthogonal response" removes
    one direction out of C and therefore only ~1/C of the pooled energy
    (measured at 0.02%-0.74%; see ``tools/analysis/audit_orthonet_attention.py``).
    The replacement is an Orthogonal Subspace Projection (Harsanyi & Chang):
    subtract a learned background prototype, then project out a learned
    orthonormal basis of rank ``k``, so the removed share is ``k/C`` and is
    explicit. A depthwise strip-pooling branch adds spatially resolved,
    orientation-aware context at O(H+W) cost, which the global average pool
    cannot express.

Differences from the design note worth knowing
---------------------------------------------
* The note's 3.4 suggested fusing the strip descriptors into a C-dimensional
  vector to keep ``fc.0`` shape-compatible. Collapsing a strip profile to a
  scalar is exactly the global average it was meant to replace, so this
  implementation keeps the channel gate and the spatial gate separate: the
  channel gate stays the legacy-compatible MLP, and the strip branch produces a
  multiplicative spatial gate. Both are identity at initialization.
* The note specified a QR/polar orthonormal basis. That was implemented first
  and rejected: ``torch.linalg.eigh`` has no usable gradient at a zero or
  degenerate basis, and it produced NaN gradients after the first optimizer
  step, which then made every later ``eigh`` fail to converge. The projection
  is now the ridge form in :func:`project_out_subspace`, which is smooth
  everywhere and exactly the identity at a zero basis. As a consequence the
  basis is randomly initialized rather than zero: a zero basis is a stationary
  point of the ridge projection.
* SOGC is rejected rather than silently ignored. SOGC calibrates
  ``OrthogonalChannelAttention``'s response; the OSP residual is a different
  statistic and would need its own source-statistics design. Failing closed is
  the repository's convention for this.
* ``init_weights`` re-applies the identity initialization because mmdet's
  ``ResNet`` installs a default Kaiming ``init_cfg`` when the caller passes
  ``init_cfg=None``, and that init walks every ``Conv2d`` in the tree.
"""

