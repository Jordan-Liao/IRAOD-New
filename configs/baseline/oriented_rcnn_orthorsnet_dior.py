"""Fully supervised OrthoRSNet source detector on clean DIOR OBB data.

OrthoRSNet adds the three remote-sensing modules of
``ORTHONET_RS_V2_DESIGN.txt`` to the OrthoNet layout:

``radiometric_cfg``  M1, a CFAR-style local contrast front end.
``stem_cfg``         M2, a directional filter bank generated by rotating one
                     learnable template to four orientations. Additive and
                     zero-initialized beside ``conv1``, so the ImageNet stem
                     weights still inflate in unchanged.
``attn_cfg``         M3, an Orthogonal Subspace Projection channel gate plus a
                     depthwise strip-pooled spatial gate.

All three are exact identities at initialization (verified: the backbone
reproduces ResNet-50 bit-for-bit on C2..C5), which is what makes this a fair
comparison against ``oriented_rcnn_orthonet_dior.py`` -- the only differences
between the two runs are the modules themselves.

This is the source model for DIOR source-free adaptation.  Its detector
structure is deliberately shared with the DIOR VLST configuration so a source
checkpoint can initialize both the student and the EMA teacher without any
missing backbone keys.
"""

_base_ = './oriented_rcnn_orthonet_dior.py'

model = dict(
    backbone=dict(
        _delete_=True,
        type='OrthoRSNet',
        depth=50,
        reduction=16,
        in_channels=3,
        num_stages=4,
        out_indices=(0, 1, 2, 3),
        # M1: local contrast normalisation at full resolution.
        radiometric_cfg=dict(
            enabled=True,
            window=5,
            eps=1e-4,
            gamma=0.5,
            hidden_channels=16,
            learnable_affine=True,
            log_input=False,
            use_variance=True),
        # M2: four orientations, one 7x7 template rotated to each. 6.8 K
        # parameters and ~0.8% extra FLOPs at 800x800.
        stem_cfg=dict(
            enabled=True,
            orientations=(0, 45, 90, 135),
            dir_kernel_size=7,
            dir_channels=8,
            renormalize=True),
        # M3: basis_rank=32 removes k/C of the pooled energy -- 12.5% at C2
        # and 1.6% at C5 -- against the ~1/C (0.05%-0.4%) of the legacy
        # orthogonal attention.
        attn_cfg=dict(
            enabled=True,
            basis_rank=32,
            strip_pool=True,
            strip_kernel=7,
            identity_init=True,
            basis_ridge=1e-3),
        frozen_stages=1,
        norm_eval=True,
        style='pytorch',
        init_cfg=dict(
            type='Pretrained', checkpoint='torchvision://resnet50')))

optimizer = dict(
    paramwise_cfg=dict(
        custom_keys={
            # Legacy OrthoNet key; absent from OrthoRSNet, kept so a shared
            # paramwise block stays valid for both backbones.
            'ortho_vector': dict(decay_mult=0.0),
            # The OSP projection is a ridge-normalised projection: it depends
            # on the column space of bg_basis only, so its scale carries no
            # function and weight decay on it is pure noise.
            'bg_basis': dict(decay_mult=0.0),
        }))

work_dir = './work_dirs/orthorsnet_dior_source_seed42'
